/**
 * Преобразования sRGB ↔ Oklab. Нужны для варианта «одно число» (CSS-only LQIP),
 * где базовый цвет квантуется именно в Oklab — он перцептивно равномерен,
 * поэтому грубое квантование по 2–3 бита не даёт резких скачков оттенка.
 */

/** Снимает гамма-коррекцию с одного канала sRGB (0..255) → линейный 0..1. */
function srgbToLinear(c) {
  const v = c / 255;
  return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
}

/** Накладывает гамма-коррекцию: линейный 0..1 → канал sRGB 0..255. */
function linearToSrgb(v) {
  const c = v <= 0.0031308 ? v * 12.92 : 1.055 * v ** (1 / 2.4) - 0.055;
  return Math.max(0, Math.min(255, Math.round(c * 255)));
}

/**
 * Переводит цвет sRGB в координаты Oklab.
 * @param r Красный канал, 0..255.
 * @param g Зелёный канал, 0..255.
 * @param b Синий канал, 0..255.
 * @returns `{ L, a, b }`, где L — светлота 0..1, a/b — оси примерно −0.4..0.4.
 */
export function rgbToOklab(r, g, b) {
  const lr = srgbToLinear(r);
  const lg = srgbToLinear(g);
  const lb = srgbToLinear(b);

  const l = Math.cbrt(0.4122214708 * lr + 0.5363325363 * lg + 0.0514459929 * lb);
  const m = Math.cbrt(0.2119034982 * lr + 0.6806995451 * lg + 0.1073969566 * lb);
  const s = Math.cbrt(0.0883024619 * lr + 0.2817188376 * lg + 0.6299787005 * lb);

  return {
    L: 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    a: 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    b: 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  };
}

/**
 * Переводит координаты Oklab обратно в sRGB.
 * @returns `{ r, g, b }` — каналы 0..255, обрезанные по границам гаммы.
 */
export function oklabToRgb(L, a, b) {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;

  return {
    r: linearToSrgb(4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s),
    g: linearToSrgb(-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s),
    b: linearToSrgb(-0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s),
  };
}

/** Форматирует канал в двузначный hex. */
const hex2 = (n) => n.toString(16).padStart(2, '0');

/** Собирает `#rrggbb` из каналов 0..255. */
export function toHex(r, g, b) {
  return `#${hex2(r)}${hex2(g)}${hex2(b)}`;
}
