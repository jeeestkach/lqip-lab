/**
 * Прогрев: собираем страницы до того, как за ними придут.
 *
 * ── Что такое прогрев и почему он нужен ─────────────────────────────────────
 * Движок JavaScript не компилирует код заранее. Сначала он исполняет байт-код
 * толкователем, считая, сколько раз какая функция вызвана; и только когда
 * функция становится «горячей», компилирует её в машинный код с учётом того,
 * какие типы через неё реально проходили. Отсюда первые запросы дороже
 * последующих: тот же самый код исполняется медленнее, потому что оптимизации
 * ещё не построены. Замер на нашем сервере: первый ответ 144 мс, установившийся
 * 3,14 мс — разница в сорок пять раз, и она целиком про разогрев.
 *
 * Ответ на вопрос «можно ли прогреть до первого запроса»: да, ровно этим здесь
 * и занимаемся. Никакой особой техники не нужно — надо просто выполнить тот же
 * код несколько раз. Ходим к себе по HTTP, а не зовём функции напрямую:
 * прогреть нужно ВЕСЬ путь, включая маршрутизацию, сборку заголовков и сжатие.
 *
 * Второй, не менее важный итог: к первому настоящему посетителю страницы уже
 * лежат готовыми в кеше — прогрев наполняет его попутно.
 *
 * ── Чего прогрев НЕ делает ──────────────────────────────────────────────────
 * Он не ускоряет установившийся режим: горячий код от лишних прогонов быстрее
 * не становится. Экономится ровно первый десяток запросов, и только он.
 */

/** Что прогреваем. Совпадает со списком кешируемых страниц. */
const PAGES = ['/', '/demo/ssr', '/demo/csr', '/compare', '/why'];

/**
 * Сколько раз пройти по каждой странице.
 *
 * Три — компромисс, а не магия. Первый проход дороже всех (толкователь плюс
 * загрузка модулей), второй заметно дешевле, третий уже близок к установившемуся.
 * Дальше выигрыш не окупает задержку старта.
 */
const ROUNDS = 3;

/** Порт, на котором себя же и опрашиваем. */
const PORT = process.env.PORT ?? process.env.NITRO_PORT ?? '3000';

/**
 * Пауза перед началом.
 *
 * Плагины исполняются ДО того, как сервер начнёт слушать порт, а хука
 * «сервер готов» в Nitro нет — я его предположил, и его не оказалось.
 * Поэтому просто ждём: сотни миллисекунд с запасом хватает, чтобы слушатель
 * встал, а если нет — обращения просто не удадутся, и прогрева не будет.
 */
const DELAY_MS = 400;

export default defineNitroPlugin(() => {
  void (async () => {
    await new Promise((resolve) => setTimeout(resolve, DELAY_MS));

    const started = Date.now();
    let done = 0;

    for (let round = 0; round < ROUNDS; round++) {
      for (const path of PAGES) {
        try {
          // Просим сжатие: иначе останется непрогретой ветка brotli,
          // а это самый дорогой участок пути.
          const res = await fetch(`http://127.0.0.1:${PORT}${path}`, {
            headers: { 'accept-encoding': 'br, gzip' },
          });
          await res.arrayBuffer();
          done += 1;
        } catch {
          // Прогрев — удобство, а не условие работы. Не вышло — не беда.
        }
      }
    }

    console.log(`[warmup] прогрето обращений: ${done} за ${Date.now() - started} мс`);
  })();
});
