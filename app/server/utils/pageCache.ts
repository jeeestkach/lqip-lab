/**
 * Кеш готовых страниц: отрисовка один раз на вариант, а не на посетителя.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * Витрина каталога одинакова для всех: она не подстраивается ни под кого лично.
 * Значит собирать её на каждый запрос незачем — достаточно собрать один раз
 * и раздавать готовое. Замер до кеша (медианы, 25 прогонов, локально):
 * отрисовка 3,14 мс, подсчёт версии 0,23 мс, сжатие 2,11 мс при первом обращении.
 * Всё это здесь становится одним поиском по ключу.
 *
 * ── Ключ — вариант страницы, а не пользователь ──────────────────────────────
 * Ключом служит адрес плюс те параметры, которые действительно меняют вывод.
 * Сегодня такой параметр один — ширина превью. Появится персонализация —
 * в ключ добавится признак группы, и вариантов станет столько же, сколько групп;
 * на число посетителей это по-прежнему не влияет.
 *
 * ── Почему только память ────────────────────────────────────────────────────
 * Намеренно. В готовой странице зашиты адреса файлов сборки, и переживи такой
 * кеш обновление образа — он раздавал бы разметку, ссылающуюся на исчезнувшие
 * скрипты. Память умирает вместе с контейнером, то есть ровно тогда, когда
 * содержимое устаревает. Redis тут не улучшение, а способ пережить пересборку
 * с испорченным содержимым: понадобится он, когда появится несколько узлов,
 * и вместе с ним понадобится ключ, включающий версию сборки.
 */

/** Готовая страница со всеми представлениями. */
export interface CachedPage {
  /** Разметка как есть. Нужна для клиентов без сжатия. */
  html: string;
  /** Версия документа — тот же `etag`, что уедет клиенту. */
  etag: string;
  /** Сжатые представления по названию кодировки. */
  encoded: Map<string, Buffer>;
}

/**
 * Адреса, которые имеет смысл держать готовыми.
 *
 * Список явный: страница загрузки сюда не входит — её вывод зависит от того,
 * что лежит в хранилище прямо сейчас, и раздавать её из кеша значило бы
 * показывать вчерашний список загруженных файлов.
 */
const CACHEABLE = new Set(['/', '/compare', '/demo/ssr', '/demo/csr', '/why']);

/**
 * Параметры адреса, влияющие на вывод.
 *
 * Всё остальное в ключ не входит и, более того, ОТМЕНЯЕТ кеширование целиком:
 * незнакомый параметр может значить что угодно, и подсунуть под него готовую
 * страницу — значит однажды отдать не то. Побочная польза: разрушители кеша
 * из демонстрации (`?cold=`, `?x=`) сами собой проходят мимо, и «холодный»
 * прогон остаётся честно холодным.
 */
const KEY_PARAMS = ['ph'];

/** Готовые страницы. Ключ — вариант, а не посетитель. */
const pages = new Map<string, CachedPage>();

/** Потолок: вариантов у демки единицы, счёт идёт на десятки. */
const LIMIT = 64;

/**
 * Ключ варианта страницы.
 *
 * @param path Путь без строки запроса.
 * @param query Разобранные параметры адреса.
 * @returns Ключ, либо `null` — если эту страницу кешировать нельзя.
 */
export function pageCacheKey(path: string, query: Record<string, unknown>): string | null {
  if (!CACHEABLE.has(path)) return null;
  const keys = Object.keys(query);
  if (keys.some((k) => !KEY_PARAMS.includes(k))) return null;
  const parts = KEY_PARAMS.filter((k) => query[k] !== undefined).map((k) => `${k}=${String(query[k])}`);
  return parts.length ? `${path}?${parts.join('&')}` : path;
}

/** Достаёт готовую страницу. */
export function getPage(key: string): CachedPage | undefined {
  return pages.get(key);
}

/** Кладёт готовую страницу, вытесняя самую старую при переполнении. */
export function setPage(key: string, page: CachedPage): void {
  if (pages.size >= LIMIT && !pages.has(key)) {
    const oldest = pages.keys().next().value;
    if (oldest) pages.delete(oldest);
  }
  pages.set(key, page);
}

/**
 * Сбрасывает кеш целиком.
 *
 * Вызывается засевом: каталог изменился — все страницы, где он показан,
 * устарели разом. Сбрасывать выборочно незачем, вариантов единицы.
 */
export function invalidatePages(): void {
  pages.clear();
}

/** Сколько вариантов сейчас готово. Для проверки и для отладки. */
export function pageCacheSize(): number {
  return pages.size;
}
