/**
 * Кеш ответов каталога и версия набора товаров.
 *
 * ── Зачем версия ────────────────────────────────────────────────────────────
 * Раньше ответы жили с `max-age=30`, и через полминуты браузер переспрашивал
 * весь каталог заново — три условных запроса по обороту сети каждый. При
 * задержке 150 мс это около 450 мс, тогда как серверный кеш экономит 9 мс.
 * То есть заголовок здесь важнее любой работы на сервере.
 *
 * Каталог при этом меняется ровно один раз — при засеве. Значит его можно
 * пометить версией и отдавать с `immutable`: адрес с версией никогда не
 * протухает, а сменится набор — сменится и адрес.
 *
 * ── Зачем кеш ответов ───────────────────────────────────────────────────────
 * Замер на сервере разложил стоимость ответа: brotli 2,41 мс (81 %), сборка
 * 0,53 мс, чтения с диска на горячем пути нет вовсе. Под нагрузкой эти четыре
 * миллисекунды превращаются в пятьдесят: Nitro однопоточный, и синхронное
 * сжатие блокирует цикл событий вместе с отрисовкой страниц.
 *
 * Кеш готовых сжатых байтов снимает и то и другое: 313 → 2 915 запросов
 * в секунду, p50 51,3 → 6,4 мс, ценой 288 КБ памяти.
 *
 * Redis для этого не нужен и вреден: петля до него 0,521 мс против 0,0002 мс
 * у памяти — в две с половиной тысячи раз дороже, то есть он съел бы пятую
 * часть экономии, ради которой ставится.
 *
 * ── Почему память переживёт пересборку, а кеш страниц не мог ────────────────
 * В готовой странице зашиты адреса файлов сборки, поэтому её кеш обязан
 * умирать с контейнером. В ответе API адреса только вида `/cdn/<sha256>/…` —
 * они адресуются содержимым и переживают любую пересборку. Здесь память
 * выбрана не из осторожности, а потому что быстрее всего.
 */

/** Готовый ответ во всех представлениях. */
export interface CachedResponse {
  /** Несжатое тело — для клиентов без сжатия. */
  body: string;
  /** Версия ответа: по ней отвечаем 304, не собирая тело. */
  etag: string;
  /** Сжатые представления по названию кодировки. */
  encoded: Map<string, Buffer>;
}

/**
 * Версия набора товаров.
 *
 * Меняется при засеве и ни при чём больше. Клиент получает её в ответе
 * и подставляет в следующие запросы — тогда ответ помечается `immutable`.
 */
let version = 1;

/** Готовые ответы. Ключ — вариант запроса, а не посетитель. */
const responses = new Map<string, CachedResponse>();

/**
 * Потолок хранилища.
 *
 * Вариантов немного: четыре ширины превью на четыре порции по 40 из 149
 * товаров — шестнадцать. Запас взят на случай других размеров порции.
 */
const LIMIT = 64;

/** Текущая версия набора товаров. */
export function catalogVersion(): number {
  return version;
}

/**
 * Объявляет набор изменившимся: версия растёт, готовые ответы выбрасываются.
 * Вызывается засевом — единственным местом, где каталог меняется.
 */
export function bumpCatalogVersion(): void {
  version += 1;
  responses.clear();
}

/** Достаёт готовый ответ. */
export function getResponse(key: string): CachedResponse | undefined {
  return responses.get(key);
}

/** Кладёт готовый ответ, вытесняя самый старый при переполнении. */
export function setResponse(key: string, value: CachedResponse): void {
  if (responses.size >= LIMIT && !responses.has(key)) {
    const oldest = responses.keys().next().value;
    if (oldest) responses.delete(oldest);
  }
  responses.set(key, value);
}

/** Сколько вариантов ответа сейчас готово. Для проверки и отладки. */
export function responseCacheSize(): number {
  return responses.size;
}
