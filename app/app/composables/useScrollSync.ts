/**
 * Совместная прокрутка двух ОТДЕЛЬНЫХ вкладок одного каталога.
 *
 * Вкладки — самостоятельные документы одного происхождения, открытые рядом.
 * Общего родителя у них нет, поэтому схема `compare.vue` (полоса родителя —
 * единственный источник правды, кадры только исполняют) здесь неприменима:
 * прокручивать может любая из вкладок, и вторая обязана повторить.
 *
 * ── Что передаём ───────────────────────────────────────────────────────────
 * НЕ пиксели и НЕ долю прокрутки, а ЯКОРЬ: «какой товар стоит у верхней кромки
 * и на сколько он ушёл за неё». Причины по порядку важности:
 *
 *   1. Доля неприменима физически. У клиентской страницы в первый момент нет
 *      ни одной карточки: `scrollHeight - innerHeight` равен нулю, доля — это
 *      деление на ноль. Позже, когда у серверной 120 карточек, а у клиентской
 *      40, доля 0,5 означает у них РАЗНЫЙ товар. Доля соотносит два документа
 *      пропорционально, а они показывают один и тот же каталог — соотносить
 *      надо товар с товаром.
 *   2. Пиксели не переносятся между окнами. Сетка — `auto-fill minmax(190px)`:
 *      в узком окне три колонки, в широком шесть, и сороковая карточка стоит
 *      на совершенно разной высоте. То же при другом масштабе страницы.
 *   3. Якорь не шевелится от догрузки. Порция всегда приклеивается СНИЗУ, то
 *      есть под якорем, и его пиксельная позиция не меняется. Доля же меняется
 *      от каждой порции — отсюда взялось бы дёрганье.
 *
 * ── Как догоняем ───────────────────────────────────────────────────────────
 * Якорь — не команда «встань сюда», а ЦЕЛЬ. Если названной карточки в ленте
 * ещё нет, вкладка прижимается к своему низу, заказывает следующую порцию и
 * пробует снова на каждом изменении длины ленты. Догон снимается, как только
 * цель достигнута или человек взялся за полосу сам.
 *
 * ── Почему нет петли ───────────────────────────────────────────────────────
 * Два независимых запрета, и каждого хватило бы поодиночке.
 *
 *   1. Вкладка рассылает только те позиции, до которых доехала САМА. «Сама» —
 *      это сравнение с последней позицией, применённой по чужой указке
 *      (`appliedY`): совпало — отражение, молчим. Признак содержательный,
 *      а не временной, поэтому нечего подбирать и нечему протухать.
 *   2. Рассылает только ВЕДУЩАЯ вкладка (`driving`). Ведущей становятся,
 *      взявшись за полосу; перестают — получив чужое состояние. Ведомая молчит
 *      физически, что бы ни показал её обработчик прокрутки.
 *
 * Второй запрет добавлен не для симметрии. При РАЗНОЙ ширине окон пересчёт
 * якоря туда-обратно не является точным тождеством: карточка у кромки
 * определяется рядом, а ряды набираются из разного числа колонок. Прогон
 * модели (5 колонок против 4) показал, что вырвавшееся эхо не раскачивается —
 * оно сходится за пару кругов, — но успевает сместить обе вкладки на четыре
 * ряда, до 1520 пикселей. При одинаковой ширине смещение ровно нулевое.
 * Признак ведущего убирает и этот случай: ведомой нечего рассылать.
 */

/**
 * Положение в ленте, независимое от ширины окна и длины документа.
 */
export interface ScrollAnchor {
  /** Сквозной номер карточки у верхней кромки. `-1` — карточек нет вовсе. */
  i: number;
  /** Доля внутрь этой карточки: 0 — её верх на кромке, 1 — низ. Может быть меньше нуля, если кромка выше сетки. */
  f: number;
  /** Абсолютная позиция отправителя, пиксели. Запасной вариант, пока ленты нет. */
  y: number;
  /** Длина ленты у отправителя — по ней видно, насколько мы отстали. */
  n: number;
}

/** Что вкладки говорят друг другу. */
type SyncMessage =
  /** Где я сейчас. `to` заполнен только у ответа новичку — остальные его пропустят. */
  | { t: 'state'; from: string; to?: string; a: ScrollAnchor }
  /** Я только что открылась и не знаю, где все. */
  | { t: 'hello'; from: string }
  /** Я закрываюсь. */
  | { t: 'bye'; from: string };

export interface ScrollSyncOptions {
  /** Имя канала. Одинаково у всех вкладок, которые ходят вместе. */
  channel?: string;
  /** Селектор карточки: по нему строится указатель позиций. */
  itemSelector?: string;
  /** Длина ленты сейчас. Реактивна: её изменение перезапускает догон. */
  count: MaybeRefOrGetter<number>;
  /** Всё ли уже показано — дальше тянуть нечего. */
  exhausted: MaybeRefOrGetter<boolean>;
  /** Заказать следующую порцию. Догон зовёт её, когда цель за пределами ленты. */
  loadMore: () => Promise<void>;
  /** Синхронизировать ли вообще. По умолчанию — да, кроме случая внутри iframe. */
  enabled?: MaybeRefOrGetter<boolean>;
}

export interface ScrollSyncApi {
  /** Есть ли на канале хоть одна другая вкладка. */
  connected: Readonly<Ref<boolean>>;
  /** Ведём ли мы: за полосу взялись здесь, остальные повторяют. */
  driving: Readonly<Ref<boolean>>;
  /** Догоняем ли соседа: цель названа, а карточки до неё ещё не приехали. */
  chasing: Readonly<Ref<boolean>>;
  /** Насколько мы отстали по числу карточек. Ноль — не отстаём. */
  behind: Readonly<Ref<number>>;
}

/** Допуск совпадения позиций, пиксели. Меньше — уже дрожание округлений. */
const EPS = 2;

/** Повтор заказа порции, если сеть промолчала. Миллисекунды. */
const RETRY_MS = 1000;

/** Клавиши, которыми человек прокручивает страницу. */
const SCROLL_KEYS = new Set([
  'ArrowUp', 'ArrowDown', 'PageUp', 'PageDown', 'Home', 'End', ' ', 'Spacebar',
]);

/**
 * Подключает вкладку к общей прокрутке.
 *
 * @param opts Лента, из которой строятся якоря, и способ дозаказать порцию.
 * @returns Состояние связи — для подписи в интерфейсе; вся работа идёт сама.
 */
export function useScrollSync(opts: ScrollSyncOptions): ScrollSyncApi {
  const channelName = opts.channel ?? 'demo:scroll';
  const itemSelector = opts.itemSelector ?? '.pcard';

  /**
   * Номер этой вкладки.
   *
   * Для отсева СВОИХ сообщений не нужен: BroadcastChannel принципиально
   * не доставляет отправителю его собственные посылки. Нужен, чтобы считать
   * соседей и не отвечать на своё же приветствие, если канал когда-нибудь
   * заменят на SharedWorker, который доставляет всем.
   */
  const id = Math.random().toString(36).slice(2, 10);

  const peers = new Set<string>();
  const connected = ref(false);
  const chasing = ref(false);
  const behind = ref(0);

  /**
   * Ведём ли мы прокрутку.
   *
   * Одинокая вкладка ведёт себя сама — отсюда `true` по умолчанию. Дальше признак
   * ходит между вкладками по двум правилам: берётся, когда человек взялся за
   * полосу здесь; теряется, когда пришло чужое состояние. Правила не пересекаются
   * и не требуют арбитра — тот, кого трогают последним, и ведёт.
   *
   * Ведомая вкладка НЕ рассылает ничего. Это отсекает не только эхо, но и второй
   * дефект: отстающая вкладка, ползущая к своему низу во время догона, иначе
   * тянула бы ведущую назад.
   */
  const driving = ref(true);

  let bc: BroadcastChannel | null = null;

  // ────────────────────────────── указатель раскладки ──────────────────────

  /** Верх каждой карточки в координатах документа. Неубывающий: сетка идёт рядами. */
  let tops: number[] = [];
  /** Высота каждой карточки — нужна, чтобы считать долю внутрь неё. */
  let heights: number[] = [];
  /** Раскладка изменилась, указатель надо перестроить. */
  let stale = true;

  /**
   * Перестраивает указатель позиций карточек.
   *
   * Читает прямоугольники всех карточек разом — полторы сотни чтений, около
   * трети миллисекунды. Делается ТОЛЬКО при изменении раскладки, никогда
   * в обработчике прокрутки: там любое чтение геометрии стоило бы пересчёта
   * раскладки на каждом кадре.
   */
  function rebuild(): void {
    const nodes = document.querySelectorAll<HTMLElement>(itemSelector);
    const sy = window.scrollY;
    tops = new Array(nodes.length);
    heights = new Array(nodes.length);
    for (let k = 0; k < nodes.length; k += 1) {
      const r = nodes[k]!.getBoundingClientRect();
      tops[k] = r.top + sy;
      heights[k] = r.height;
    }
    stale = false;
  }

  /**
   * Последняя карточка, чей верх не ниже указанной линии.
   *
   * Именно ПОСЛЕДНЯЯ, а не первая в ряду, и это принципиально. Карточки одного
   * ряда имеют одинаковый верх; если брать первую, вкладка с пятью колонками
   * назовёт карточку 10, а вкладка с тремя — 12, и они будут бесконечно
   * поправлять друг друга. Последняя в ряду вычисляется одинаково при любом
   * числе колонок, поэтому пересчёт якоря туда и обратно даёт ту же точку.
   *
   * @param y Линия в координатах документа.
   * @returns Номер карточки; 0, если линия выше всей сетки.
   */
  function lastAtOrAbove(y: number): number {
    let lo = 0;
    let hi = tops.length - 1;
    let ans = 0;
    while (lo <= hi) {
      const mid = (lo + hi) >> 1;
      if (tops[mid]! <= y) {
        ans = mid;
        lo = mid + 1;
      } else {
        hi = mid - 1;
      }
    }
    return ans;
  }

  /** Куда вообще можно прокрутить документ. */
  function maxScrollY(): number {
    return Math.max(0, document.documentElement.scrollHeight - window.innerHeight);
  }

  /** Снимает текущее положение в виде якоря. */
  function readAnchor(): ScrollAnchor {
    const y = window.scrollY;
    if (stale) rebuild();
    if (!tops.length) return { i: -1, f: 0, y, n: 0 };
    const i = lastAtOrAbove(y);
    return { i, f: (y - tops[i]!) / (heights[i] || 1), y, n: tops.length };
  }

  /**
   * Переводит чужой якорь в свою пиксельную позицию.
   * @returns Позиция; `null`, если такой карточки в ленте ещё нет.
   */
  function anchorToY(a: ScrollAnchor): number | null {
    if (stale) rebuild();
    // У соседа карточек нет — сравнивать нечего, остаются голые пиксели.
    if (a.i < 0) return a.y;
    if (a.i >= tops.length) return null;
    return tops[a.i]! + a.f * (heights[a.i] || 0);
  }

  // ────────────────────────────── подавление эха ───────────────────────────

  /**
   * Позиция, в которую мы встали ПО ЧУЖОЙ УКАЗКЕ, либо `null`, если за полосу
   * взялся человек.
   *
   * Это и есть подавление эха, и оно содержательное, а не временное. Прокрутка
   * из кода вызывает событие `scroll` асинхронно, на ближайшем кадре, поэтому
   * флаг, снимаемый «на следующем тике» или по таймеру, — угадывание: снимешь
   * рано — уйдёт эхо, поздно — потеряешь настоящее движение человека. Здесь
   * снимать нечего по времени: событие сравнивается со значением. Совпало —
   * это наше собственное отражение, молчим. Разошлось хотя бы на три пикселя —
   * значит, полосу двинул человек, и `appliedY` тут же обнуляется.
   *
   * Единственная плата: первые два пикселя движения человека от применённой
   * точки не рассылаются. Их и не видно.
   *
   * Подстраховок ещё две, и они делают петлю невозможной, даже если это
   * сравнение однажды ошибётся:
   *   · применение якоря ИДЕМПОТЕНТНО — вкладка, получившая свою же позицию,
   *     никуда не сдвинется, и отражение умрёт на первом же шаге, а не начнёт
   *     раскачиваться;
   *   · BroadcastChannel не доставляет отправителю его собственные сообщения,
   *     поэтому «сам себе сказал» невозможно в принципе.
   */
  let appliedY: number | null = null;

  /**
   * Ставит документ в указанную позицию как применение чужого состояния.
   *
   * Всегда мгновенно. Плавная прокрутка тянется около трёхсот миллисекунд, за
   * которые придёт полтора десятка новых состояний, каждое перенацелит анимацию
   * — вместо слежения получилось бы раскачивание. Частота сообщений и так равна
   * частоте кадров, поэтому движение выглядит непрерывным без всякой анимации.
   */
  function scrollToY(y: number): void {
    const target = Math.max(0, Math.min(y, maxScrollY()));
    appliedY = target;
    window.scrollTo({ top: target, behavior: 'instant' as ScrollBehavior });
  }

  // ────────────────────────────── догон ────────────────────────────────────

  /** Последнее, что сказал сосед. Не стирается: нужно при возврате из фона. */
  let remote: ScrollAnchor | null = null;
  /** Цель, до которой лента ещё не доросла. */
  let pending: ScrollAnchor | null = null;
  let retryTimer: ReturnType<typeof setTimeout> | undefined;

  /** Прекращает догон: цель достигнута либо отменена. */
  function stopChase(): void {
    pending = null;
    chasing.value = false;
    behind.value = 0;
    clearTimeout(retryTimer);
  }

  /**
   * Точно ли тянуть больше нечего.
   *
   * Само по себе `exhausted` из ленты в первый момент ВРЁТ: оно определено как
   * «карточек не меньше, чем всего», а у клиентской стратегии сразу после
   * загрузки и то и другое равно нулю — ноль не меньше нуля, и лента объявляет
   * себя исчерпанной, ещё не сходив за первой порцией. Поймано браузерным
   * прогоном: вкладка получала цель, верила в исчерпанность и замирала на нуле.
   * Пустая лента исчерпанной не бывает.
   */
  function reallyExhausted(): boolean {
    return toValue(opts.exhausted) && toValue(opts.count) > 0;
  }

  /**
   * Заказывает следующую порцию ради недостижимой цели.
   *
   * Собственная догрузка ленты сюда не дотянется: она заказывает порцию, подходя
   * к низу ПРОКРУТКОЙ, а отставшая вкладка уже стоит у своего низа и прокрутить
   * дальше физически не может. Поэтому тянем явно.
   *
   * Ждём не таймером, а изменением длины ленты — оно и есть событие «порция
   * приехала». Таймер здесь только на случай отказа сети: `loadMore` глотает
   * ошибку молча, и без повтора догон завис бы навсегда.
   */
  function chase(): void {
    clearTimeout(retryTimer);
    if (!pending) return;
    if (reallyExhausted()) {
      // Тянуть больше нечего — сосед видит то, чего у нас не будет. Стоим у низа.
      stopChase();
      scrollToY(maxScrollY());
      return;
    }
    chasing.value = true;
    behind.value = Math.max(0, pending.i + 1 - toValue(opts.count));
    void opts.loadMore();
    retryTimer = setTimeout(chase, RETRY_MS);
  }

  /**
   * Применяет последнее полученное состояние.
   *
   * Цель недостижима — не ошибка и не повод молчать: встаём как можно ближе,
   * то есть у своего низа, и запускаем догон. Пользователь видит отстающую
   * вкладку на её последней карточке, а когда порция приезжает — она встаёт
   * на ТОТ ЖЕ ТОВАР, а не на приблизительный пиксель.
   */
  function applyRemote(): void {
    const a = remote;
    if (!a) return;

    const y = anchorToY(a);

    /*
     * Цель бывает недостижима ДВУМЯ разными способами, а лечатся они одинаково —
     * дозаказом порции:
     *   · такой карточки в ленте ещё нет (`null`) — обычный случай отставания;
     *   · карточка есть, но документ короче, чем нужно, чтобы поднять её к
     *     кромке. Так выходит у окна, где колонок больше: те же товары
     *     укладываются в меньшее число рядов, и прокручивать просто некуда.
     *     Проверено в браузере: окно на 5 колонок против окна на 2 упиралось
     *     в свой предел 257 px при цели 741 px.
     * Ещё порция удлиняет документ и снимает упор.
     */
    if (y === null || y > maxScrollY() + EPS) {
      if (!reallyExhausted()) {
        pending = a;
        scrollToY(maxScrollY());
        chase();
        return;
      }
      // Лента кончилась. Ближе к цели не встать — прижимаемся к низу.
      // Товар при этом всё равно на экране, просто не у верхней кромки.
      stopChase();
      scrollToY(y ?? maxScrollY());
      return;
    }

    stopChase();
    scrollToY(y);
  }

  // ────────────────────────────── канал ────────────────────────────────────

  /**
   * Последний собственный якорь ведущей вкладки.
   *
   * Нужен, чтобы пережить смену раскладки: пиксель после неё указывает
   * на другую карточку, а якорь — на ту же самую.
   */
  let local: ScrollAnchor | null = null;

  /** Рассылает текущее положение. Отражения чужих применений отсеиваются здесь. */
  function publish(): void {
    if (!bc || !driving.value) return;
    const y = window.scrollY;
    if (appliedY !== null && Math.abs(y - appliedY) <= EPS) return;
    // Разошлось — значит, полосу двинул человек. Дальше рассылаем без оглядки.
    appliedY = null;
    local = readAnchor();
    bc.postMessage({ t: 'state', from: id, a: local } satisfies SyncMessage);
  }

  /**
   * Рассылает положение безусловно, минуя отсев эха.
   *
   * Нужно там, где положение изменилось не от прокрутки, а от смены раскладки:
   * обычная рассылка сочла бы это чужим применением и промолчала.
   */
  function announce(): void {
    if (!bc || !driving.value) return;
    appliedY = null;
    local = readAnchor();
    bc.postMessage({ t: 'state', from: id, a: local } satisfies SyncMessage);
  }

  let sendRaf = 0;

  /**
   * Собирает пачку событий прокрутки в одну посылку за кадр.
   *
   * Именно кадр, а не таймер. На трекпаде события идут с частотой экрана — до
   * ста двадцати в секунду — и уже выровнены по кадрам; `requestAnimationFrame`
   * схлопывает пачку ровно в одно чтение, причём в тот момент кадра, когда
   * раскладка уже посчитана. Таймер на 50 мс превратил бы инерционный выбег
   * в двадцать ступенек в секунду — на соседней вкладке это видно как рывки.
   * Инерцию не нужно ни гасить, ни моделировать: она передаётся сама, потоком
   * позиций, и сосед просто повторяет ту же кривую.
   *
   * Дополнительная выгода: в фоновой вкладке кадров нет, и рассылка замирает
   * сама собой — что и требуется, фоновую вкладку никто не прокручивает.
   */
  function onScroll(): void {
    if (sendRaf) return;
    sendRaf = requestAnimationFrame(() => {
      sendRaf = 0;
      publish();
    });
  }

  /**
   * Человек взялся за руль.
   *
   * Это НЕ выводится из одной прокрутки: во время догона страница и так едет
   * сама, и колесо мыши посреди догона неотличимо от нашего же движения.
   * Поэтому слушаем ввод напрямую: колесо, палец, клавиши прокрутки и захват
   * полосы. Догон отменяется — иначе страница дёрнулась бы через секунду,
   * когда доедет заказанная порция.
   */
  function onUserInput(): void {
    driving.value = true;
    appliedY = null;
    if (pending) stopChase();
  }

  function onKeyDown(e: KeyboardEvent): void {
    if (SCROLL_KEYS.has(e.key)) onUserInput();
  }

  let applyRaf = 0;

  /** Ставит применение на ближайший кадр; в фоне применяет сразу. */
  function schedule(): void {
    // В скрытой вкладке кадров не выдают вовсе, и ожидание кадра означало бы
    // «не синхронизируемся, пока на нас не посмотрят». Сообщения при этом
    // доставляются исправно, поэтому применяем прямо в обработчике: рисовать
    // всё равно нечего, а к моменту возврата вкладка уже стоит где надо.
    if (document.hidden) {
      applyRemote();
      return;
    }
    if (applyRaf) return;
    applyRaf = requestAnimationFrame(() => {
      applyRaf = 0;
      applyRemote();
    });
  }

  function onMessage(e: MessageEvent<SyncMessage>): void {
    const m = e.data;
    if (!m || m.from === id) return;

    if (m.t === 'bye') {
      peers.delete(m.from);
      connected.value = peers.size > 0;
      return;
    }

    peers.add(m.from);
    connected.value = true;

    // Новичок только что открылся и не знает, где мы. Рассказываем — но лично
    // ему: канал общий, и без адреса ответ дёрнул бы всех остальных на нашу
    // позицию, хотя спрашивали не они.
    if (m.t === 'hello') {
      bc?.postMessage({ t: 'state', from: id, to: m.from, a: readAnchor() } satisfies SyncMessage);
      return;
    }

    if (m.to !== undefined && m.to !== id) return;

    // Ведёт тот, кто прислал. Мы — повторяем и до следующего касания молчим.
    driving.value = false;
    remote = m.a;
    schedule();
  }

  /**
   * Открывает канал.
   *
   * Отдельной функцией, потому что канал приходится закрывать и открывать
   * заново вокруг bfcache: сообщение, доставленное странице, лежащей в кеше
   * навигации, ВЫБРАСЫВАЕТ её оттуда, и возврат «назад» перестаёт быть
   * мгновенным. Пока вкладка спрятана в кеш, ей и синхронизироваться незачем.
   */
  function open(): void {
    if (bc) return;
    bc = new BroadcastChannel(channelName);
    bc.addEventListener('message', onMessage as EventListener);
    bc.postMessage({ t: 'hello', from: id } satisfies SyncMessage);
  }

  function close(): void {
    if (!bc) return;
    bc.postMessage({ t: 'bye', from: id } satisfies SyncMessage);
    bc.removeEventListener('message', onMessage as EventListener);
    bc.close();
    bc = null;
    peers.clear();
    connected.value = false;
  }

  // ────────────────────────────── жизненный цикл ───────────────────────────

  let ro: ResizeObserver | null = null;

  function onPageHide(): void {
    close();
  }

  function onPageShow(): void {
    if (!toValue(opts.enabled ?? true)) return;
    stale = true;
    open();
  }

  function onVisibility(): void {
    if (document.hidden) return;
    // Ведущая держит СВОЁ, ведомая догоняет чужое. Без проверки ведущая
    // уезжала в позицию соседа, снятую ДО того, как руль перешёл к ней, —
    // то есть в протухшую. Проверено в браузере: вкладка на y=0 прыгала
    // на позицию соседа при простом возврате из фона.
    if (driving.value) restoreLocal();
    else if (remote) applyRemote();
  }

  function onResize(): void {
    stale = true;
    // Ширина изменилась — колонок и высот стало другое количество, пиксель
    // уехал. Но товар не уехал: у ведущей есть собственный якорь, у ведомой —
    // якорь соседа. Каждая восстанавливается по своему.
    if (driving.value) restoreLocal();
    else if (remote) schedule();
  }

  /**
   * Возвращает ведущую вкладку к её собственному товару после смены раскладки.
   *
   * Своей позиции в пикселях доверять нельзя — при другом числе колонок она
   * указывает на другую карточку. Якорь запоминается при каждой рассылке.
   */
  function restoreLocal(): void {
    if (!local) return;
    const y = anchorToY(local);
    if (y !== null) scrollToY(y);
    // Раскладка изменилась — соседу надо сказать заново, иначе он останется
    // стоять по старым координатам.
    announce();
  }

  onMounted(() => {
    // Внутри кадра сравнения синхронизировать нечего: там дирижирует родитель,
    // а собственной прокрутки у документа нет вовсе.
    const enabled = opts.enabled !== undefined
      ? toValue(opts.enabled)
      : window.parent === window;
    if (!enabled || typeof BroadcastChannel === 'undefined') return;

    open();

    window.addEventListener('scroll', onScroll, { passive: true });
    window.addEventListener('resize', onResize, { passive: true });
    window.addEventListener('wheel', onUserInput, { passive: true });
    window.addEventListener('touchstart', onUserInput, { passive: true });
    window.addEventListener('mousedown', onUserInput, { passive: true });
    window.addEventListener('keydown', onKeyDown, { passive: true });
    window.addEventListener('pagehide', onPageHide);
    window.addEventListener('pageshow', onPageShow);
    document.addEventListener('visibilitychange', onVisibility);

    // Картинки места не двигают — слоты зарезервированы `aspect-ratio`, — но
    // порция карточек и перенос строки в названии двигают. Отмечаем указатель
    // устаревшим и перестраиваем лениво, при первом же обращении.
    ro = new ResizeObserver(() => {
      stale = true;
    });
    const page = document.querySelector('.demo-page');
    if (page) ro.observe(page);
  });

  onBeforeUnmount(() => {
    close();
    clearTimeout(retryTimer);
    if (sendRaf) cancelAnimationFrame(sendRaf);
    if (applyRaf) cancelAnimationFrame(applyRaf);
    ro?.disconnect();
    window.removeEventListener('scroll', onScroll);
    window.removeEventListener('resize', onResize);
    window.removeEventListener('wheel', onUserInput);
    window.removeEventListener('touchstart', onUserInput);
    window.removeEventListener('mousedown', onUserInput);
    window.removeEventListener('keydown', onKeyDown);
    window.removeEventListener('pagehide', onPageHide);
    window.removeEventListener('pageshow', onPageShow);
    document.removeEventListener('visibilitychange', onVisibility);
  });

  /*
   * Лента выросла — указатель устарел, а недостижимая цель могла стать
   * достижимой. Это и есть двигатель догона: не таймер, а приезд порции.
   *
   * Условие — «мы ведомые и цель известна», а НЕ «идёт догон». Разница вскрылась
   * в браузере: клиентская вкладка получает цель, когда карточек у неё ещё ноль,
   * догон в тот момент может быть и не начат, — и всё равно обязана встать на
   * место, как только первая порция доедет.
   */
  watch(
    () => toValue(opts.count),
    () => {
      stale = true;
      if (!driving.value && remote) applyRemote();
    },
  );

  return {
    connected: readonly(connected),
    driving: readonly(driving),
    chasing: readonly(chasing),
    behind: readonly(behind),
  };
}
