/**
 * Плагин сборки: сокращает имена классов в исходниках перед компиляцией.
 *
 * Работает ДО компилятора однофайловых компонентов (`enforce: 'pre'`), поэтому
 * получает исходный текст `.vue` целиком — и шаблон, и стили, и скрипт. Класс
 * живёт во всех трёх местах сразу, и переписать его надо разом, иначе селектор
 * перестанет находить элемент.
 *
 * Включён и в разработке тоже. Так отлаживается ровно то, что уедет клиенту:
 * расхождение «в разработке одни имена, в сборке другие» — источник ошибок,
 * которые не воспроизводятся локально.
 */

import type { Plugin } from 'vite';
import { renameClasses } from './class-map';

/** Что переписываем: свои исходники, не чужие пакеты. */
const HANDLED = /\.(vue|css|ts|mjs|js)($|\?)/;

/** Создаёт плагин сокращения имён классов. */
export function classMinifier(): Plugin {
  return {
    name: 'lqip:class-minifier',
    // До @vitejs/plugin-vue: ему должен достаться уже переписанный исходник.
    enforce: 'pre',
    transform(code, id) {
      if (id.includes('node_modules') || !HANDLED.test(id)) return null;
      const out = renameClasses(code);
      // Карта соответствия не нужна: замены не меняют число строк,
      // а имена и без того однозначно сопоставляются через class-map.ts.
      return out === code ? null : { code: out, map: null };
    },
  };
}
