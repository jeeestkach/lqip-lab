/**
 * Профили соединения и расчёт времени передачи.
 *
 * Общий код для сервера и клиента: сервер по этим числам притормаживает отдачу
 * каждого файла ровно на столько, сколько он ехал бы по такому каналу,
 * а клиент показывает те же цифры в интерфейсе. Держать таблицу в двух местах
 * нельзя — разойдутся, и демонстрация начнёт врать.
 *
 * Числа — канонические профили троттлинга Chrome DevTools, чтобы результат
 * можно было перепроверить на вкладке Network.
 */

export interface Speed {
  key: string;
  label: string;
  /** Пропускная способность канала, бит в секунду. */
  bps: number;
  /** Сетевая задержка до первого байта, мс. */
  rtt: number;
  hint: string;
}

export const SPEEDS: Speed[] = [
  { key: 'slow3g', label: 'Медленный 3G', bps: 400_000, rtt: 400, hint: '400 Кбит/с · 400 мс' },
  { key: 'slow4g', label: 'Медленный 4G', bps: 1_600_000, rtt: 150, hint: '1,6 Мбит/с · 150 мс' },
  { key: 'fast4g', label: 'Быстрый 4G', bps: 9_000_000, rtt: 85, hint: '9 Мбит/с · 85 мс' },
  { key: 'wifi', label: 'Быстрый интернет', bps: 50_000_000, rtt: 20, hint: '50 Мбит/с · 20 мс' },
  { key: 'off', label: 'Без ограничения', bps: 0, rtt: 0, hint: 'как есть' },
];

/** Находит профиль по ключу; неизвестный ключ даёт «без ограничения». */
export function findSpeed(key: string | undefined): Speed {
  return SPEEDS.find((s) => s.key === key) ?? SPEEDS[SPEEDS.length - 1]!;
}

/**
 * Сколько миллисекунд файл такого размера ехал бы по такому каналу.
 *
 * Тяжёлый файл ждёт дольше лёгкого — в этом вся разница с фиксированной
 * задержкой, которая всем даёт одинаковую паузу и потому неправдоподобна.
 *
 * @param bytes Размер файла.
 * @param speed Профиль соединения.
 * @returns Время в миллисекундах: задержка сети плюс передача.
 */
export function transferMs(bytes: number, speed: Speed): number {
  if (!speed.bps) return 0;
  return Math.round(speed.rtt + ((bytes * 8) / speed.bps) * 1000);
}
